#!/usr/bin/env python3
"""Turns tools/conditions/out/*.png + data.json (from render.mjs) into the shipped files. Idempotent. Run from the repo root.
   • public/2d/conditions/<slug>__<n>.webp       one picture per condition (sub-image)
   • public/2d/<class>/<subject>/images/dialysis.webp   the new main haemodialysis picture
   • public/2d/conditions.js                      window.VA_CONDS = { "<class>/<subject>/<image>": [ {id,img,title,desc,marks,src}, … ] }
   • assets/va-2d.js and public/2d/class10/biology/viewer.html get the haemodialysis main image (DATA + sidebar entry) """
import json, os, re, sys
from PIL import Image
root = os.getcwd()
OUT = os.path.join(root, 'tools/conditions/out')
data = json.load(open(os.path.join(OUT, 'data.json'), encoding='utf-8'))
os.makedirs(os.path.join(root, 'public/2d/conditions'), exist_ok=True)
Q = 74
def webp(src, dst, w=1280):
    im = Image.open(src).convert('RGB')
    if im.width > w: im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
    im.save(dst, 'webp', quality=Q, method=6)
    return os.path.getsize(dst)
# renders of the third-party anatomy packs must stay CC BY-SA and be credited (docs/ASSET_LICENSES.md)
PACK_TOPICS = {'ch5/heart3d', 'ch5/lungs3d', 'ch10/eye3d', 'ix2/joint3d', 'ch5/digest3d'}
CREDIT = 'Anatomy © BodyParts3D (DBCLS, CC BY-SA 2.1 JP) · Z-Anatomy (CC BY-SA 4.0), simplified render — shared under CC BY-SA 4.0'
STANDALONE = {'class10/physics/lens': 'class10/physics/convex_lens', 'class10/physics/circuit': 'class10/physics/electric_circuit', 'class10/physics/motor': 'class10/physics/electric_motor', 'class10/chemistry/ph': 'class10/chemistry/ph_testing', 'class10/chemistry/displacement': 'class10/chemistry/displacement_reaction', 'class10/chemistry/reactivity': 'class10/chemistry/reactivity_series'}
conds, total = {}, 0
for key, val in data.items():
    if key.endswith('#main'): continue
    items = []
    for c in val:
        dst = os.path.join(root, 'public/2d/conditions', c['file'].replace('.png', '.webp'))
        total += webp(os.path.join(OUT, c['file']), dst)
        it = {'id': 'c%d' % c['n'], 'img': 'conditions/' + os.path.basename(dst), 'title': c['title'], 'desc': c['desc'], 'marks': [m for m in c['marks'] if 0 <= m['x'] <= 100 and 0 <= m['y'] <= 100], 'src': '%s#%d' % (c['topic'], c['step'])}
        if c['topic'] in PACK_TOPICS: it['credit'] = CREDIT
        items.append(it)
    if items:
        conds[key] = items
js = '/* Generated by tools/conditions/build.py — condition (sub-image) pictures rendered from the atlas\'s 3D scenes. Do not edit by hand. */\nwindow.VA_CONDS=' + json.dumps(conds, ensure_ascii=False, separators=(',', ':')) + ';\nwindow.VA_COND_ALIAS=' + json.dumps({v: k for k, v in STANDALONE.items()}, separators=(',', ':')) + ';  /* standalone image id -> in-app image id */\n'
open(os.path.join(root, 'public/2d/conditions.js'), 'w', encoding='utf-8').write(js)
print('conditions:', sum(len(v) for v in conds.values()), 'images for', len(conds), 'main pictures,', round(total / 1e6, 2), 'MB')

# ---- haemodialysis main picture ----
m = data.get('class10/biology/dialysis#main')
if m:
    grp = 'class10/biology'
    dst = os.path.join(root, 'public/2d', grp, 'images/dialysis.webp'); webp(os.path.join(OUT, m['file']), dst, 1400)
    entry = {'title': 'Haemodialysis (Artificial Kidney) — हीमोडायलिसिस (कृत्रिम वृक्क)',
             'desc': 'डायलाइज़र के खोखले तंतु, रक्त-पंप, फिस्टुला, डायलिसिस-द्रव। Hollow-fibre dialyzer, blood pump, AV fistula and dialysing fluid.',
             'img': 'images/dialysis.webp', 'marks': m['marks']}
    # in-app 2D layer
    p = os.path.join(root, 'assets/va-2d.js'); s = open(p, encoding='utf-8').read()
    mm = re.search(r'const DATA=(\{.*?\});\n', s, re.S); D = json.loads(mm.group(1))
    D[grp]['dialysis'] = entry
    s = s[:mm.start(1)] + json.dumps(D, ensure_ascii=False, separators=(',', ':')) + s[mm.end(1):]
    if '"ch5/dialysis3d"' not in s:
        s = s.replace('"ch5/heart":[B10+"circulatory_system"]', '"ch5/dialysis3d":[B10+"dialysis",B10+"excretory_system"],"ch5/heart":[B10+"circulatory_system"]', 1)
    if '"ch5/nephron3d"' not in s:
        s = s.replace('"ch5/dialysis3d":[B10+"dialysis",B10+"excretory_system"],', '"ch5/dialysis3d":[B10+"dialysis",B10+"excretory_system"],"ch5/nephron3d":[B10+"excretory_system",B10+"dialysis"],', 1)
    open(p, 'w', encoding='utf-8').write(s)
    # standalone class X biology viewer
    p = os.path.join(root, 'public/2d', grp, 'viewer.html'); h = open(p, encoding='utf-8').read()
    if " dialysis:{" not in h:
        marks = json.dumps(m['marks'], ensure_ascii=False)
        block = " dialysis:{\n  title:'%s', desc:'%s',\n  img:'images/dialysis.webp',\n  marks:%s},\n" % (entry['title'], entry['desc'], marks)
        i = h.index('const DATA={') + len('const DATA={') ; h = h[:i] + '\n' + block + h[i:]
    if 'data-sub="dialysis"' not in h:
        m2 = re.search(r'    <div class="sub" data-sub="excretory_system"[^\n]*\n', h)
        row = '    <div class="sub" data-sub="dialysis" onclick="selectSub(\'dialysis\')">Haemodialysis (Artificial Kidney) — हीमोडायलिसिस</div>\n'
        h = h[:m2.end()] + row + h[m2.end():]
    open(p, 'w', encoding='utf-8').write(h)
    print('dialysis main picture added with', len(m['marks']), 'labels')
