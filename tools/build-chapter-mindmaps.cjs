#!/usr/bin/env node
/* Generates docs/CHAPTER_MINDMAPS.md: Mermaid mind map per chapter, Class IX (api/ai/curriculum.json) + Class X (tools/data + index.html Hi registry). */
const fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.resolve(__dirname,'..');
const ix=JSON.parse(fs.readFileSync(path.join(root,'api/ai/curriculum.json'),'utf8'));
const x10=JSON.parse(fs.readFileSync(path.join(__dirname,'data/class10-mindmaps.json'),'utf8'));
const src=fs.readFileSync(path.join(root,'index.html'),'utf8');
function extract(m){const a=src.indexOf(m),s=a+m.length-1;let d=0,q='',e=false;for(let i=s;i<src.length;i++){const c=src[i];if(q){if(e)e=false;else if(c==='\\')e=true;else if(c===q)q='';continue}if(c==='"'||c==="'"||c==='`'){q=c;continue}if(c==='['||c==='{')d++;else if(c===']'||c==='}'){if(--d===0)return src.slice(s,i+1)}}throw new Error('no '+m)}
const refs=new Proxy({TP:(id,title,hi,_m,summary)=>({id,title,hi,summary}),reuse:(...a)=>a[1]},{get:(t,k)=>k in t?t[k]:undefined});
const Hi=vm.runInNewContext(`(()=>(${extract('Hi=[')}))()`,refs,{timeout:2000});
const clean=t=>String(t).replace(/[()[\]{}"`<>#]/g,' ').replace(/;/g,",").replace(/\s+/g,' ').trim();
const branch=(n,items)=>items&&items.length?[`    ${clean(n)}`,...items.map(i=>`      ${clean(i)}`)]:[];
const mm=(title,branches)=>['```mermaid','mindmap',`  root((${clean(title)}))`,...branches.flat(),'```'].join('\n');
const out=[];let count={ix:0,x:0};
out.push('# Chapter-wise Mind Maps — Class IX & Class X Science (CBSE 086)','',
'> Generated by `node tools/build-chapter-mindmaps.cjs` — do not edit by hand. Class IX is built from `api/ai/curriculum.json` (repo registry `IXC`); Class X from `tools/data/class10-mindmaps.json` + the in-app `Hi` registry. Mermaid renders on GitHub; for the interactive in-app map see `docs/MIND_MAP.md`.','',
'**Scope:** Class IX = 12 chapters (2026–27 course); Class X = 13 chapters. Verify against the current CBSE syllabus/NCERT before exam use.','');
out.push('## Index','','| Class | Ch | Chapter | Unit |','|---|---|---|---|');
for(const c of ix.chapters)out.push(`| IX | ${c.number} | ${c.title} | ${c.unit} |`);
for(const c of x10.chapters)out.push(`| X | ${c.no} | ${c.title} | ${c.unit} |`);
out.push('','---','','## Class IX','');
for(const c of ix.chapters){count.ix++;
 out.push(`### IX · Ch ${c.number} — ${c.title}`,'',`*${c.unit}* · ${c.briefHi||''}`,'',
 mm(`Ch ${c.number} ${c.title}`,[branch('Key concepts',c.keyConcepts),branch('Visual lessons',c.topics.map(t=>t.title)),branch('Activities',c.activities),branch('Practicals',c.practicals.map(p=>typeof p==='string'?p:p.title||p.name||JSON.stringify(p))),branch('Review notes',c.reviewFlags)]),'');
 if(c.learningOutcomes.length)out.push('**Learning outcomes**','',...c.learningOutcomes.map(l=>`- ${l}`),'');}
out.push('---','','## Class X','');
for(const c of x10.chapters){count.x++;
 const app=Hi.find(h=>h.no===c.no);
 if(!app||app.title!==c.title)throw new Error('Class X title mismatch ch'+c.no);
 out.push(`### X · Ch ${c.no} — ${c.title}`,'',`*${c.unit}* · ${c.hi}`,'',
 mm(`Ch ${c.no} ${c.title}`,[...c.branches.map(b=>branch(b.n,b.i)),branch('Visual lessons in Vigyan Atlas',app.topics.map(t=>t.title))]),'');}
out.push(`<!-- ${count.ix} Class IX + ${count.x} Class X chapters -->`,'');
fs.writeFileSync(path.join(root,'docs/CHAPTER_MINDMAPS.md'),out.join('\n'));
console.log(`Wrote ${count.ix} Class IX + ${count.x} Class X chapter mind maps.`);
